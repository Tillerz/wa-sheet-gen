// Export file names, in the order they are written.
var exportFiles = []string{"approved.css", "style.css", "import-to-wa.yml", "basic-sheet.html.twig", "edit-form.html.twig"}

const cssHeader = "/* Generated by WA Sheet Generator. Edit custom CSS in the app, not here. */\n"

// buildExport validates p and generates the five WA files (bible 1).
// Files are only returned when there are no errors.
func buildExport(p *Project) (map[string]string, []Problem) {
	ps := validateProject(p)
	if hasErrors(ps) {
		return nil, ps
	}
	files := map[string]string{
		"approved.css":          genApprovedCSS(p),
		"style.css":             genStyleCSS(p),
		"import-to-wa.yml":      genYAML(p),
		"basic-sheet.html.twig": genTwig(p, false),
		"edit-form.html.twig":   genTwig(p, true),
	}
	ps = append(ps, checkCSS("approved.css", files["approved.css"])...)
	ps = append(ps, checkCSS("style.css", files["style.css"])...)
	ps = append(ps, checkHTML("basic-sheet.html.twig", files["basic-sheet.html.twig"])...)
	ps = append(ps, checkHTML("edit-form.html.twig", files["edit-form.html.twig"])...)
	if hasErrors(ps) {
		return nil, ps
	}
	return files, ps
}

func writeExport(folder string, files map[string]string) error {
	if err := os.MkdirAll(folder, 0o755); err != nil {
		return err
	}
	for _, name := range exportFiles {
		if err := os.WriteFile(filepath.Join(folder, name), []byte(files[name]), 0o644); err != nil {
			return err
		}
	}
	return nil
}

// ---------- escaping ----------

// htmlEscaper escapes text and attribute values. Braces are escaped too,
// so user text can never become Twig code ({{ … }} or {% … %}).
var htmlEscaper = strings.NewReplacer(
	"&", "&amp;", "<", "&lt;", ">", "&gt;", `"`, "&quot;", "'", "&#39;", "{", "&#123;", "}", "&#125;",
)

func esc(s string) string { return htmlEscaper.Replace(s) }

// twigStr is the content of a single-quoted Twig string literal.
func twigStr(s string) string {
	return strings.NewReplacer(`\`, `\\`, `'`, `\'`).Replace(s)
}

func yamlStr(s string) string {
	return `"` + strings.NewReplacer(`\`, `\\`, `"`, `\"`).Replace(s) + `"`
}

func num(v float64) string { return strconv.FormatFloat(v, 'f', -1, 64) }

// fieldClass turns a field name into its class part: hp_max → hp-max.
func fieldClass(name string) string { return strings.ReplaceAll(name, "_", "-") }

// ---------- CSS ----------

func genApprovedCSS(p *Project) string {
	var b strings.Builder
	b.WriteString(cssHeader)
	for _, f := range sheetFonts(p) {
		fmt.Fprintf(&b, "@font-face {\n  font-family: %s;\n  font-style: normal;\n  font-weight: 400;\n  src: url(%s)\n}\n", f.Name, f.URL)
	}
	if s := strings.TrimSpace(p.CustomCSS.Approved); s != "" {
		b.WriteString(s + "\n")
	}
	return b.String()
}

// sheetFonts: the project's fonts plus the library fonts its theme uses (once each).
func sheetFonts(p *Project) []Font {
	fonts := append([]Font{}, p.Fonts...)
	have := map[string]bool{}
	for _, f := range fonts {
		have[f.Name] = true
	}
	if t := findTheme(p.Theme); t != nil {
		for _, name := range t.Fonts {
			for _, lf := range fontLibrary {
				if lf.Name == name && !have[name] {
					fonts = append(fonts, lf)
					have[name] = true
				}
			}
		}
	}
	return fonts
}

func genStyleCSS(p *Project) string {
	var b strings.Builder
	b.WriteString(cssHeader)
	// Order: theme, then formats, then custom CSS, so each can override the one before.
	if t := findTheme(p.Theme); t != nil {
		b.WriteString(themeCSS(t, ".block-"+p.SheetName))
	}
	b.WriteString(genFormatCSS(p))
	if s := strings.TrimSpace(p.CustomCSS.Style); s != "" {
		b.WriteString(s + "\n")
	}
	return b.String()
}

// ---------- YAML ----------

func genYAML(p *Project) string {
	var b strings.Builder
	b.WriteString("fields:\n")
	eachFieldEntry(p.Root, func(n *Node, suffix string) {
		if suffix != "" && isConstField(n) {
			return // preset text only, nothing to save
		}
		name := propString(n, "name") + suffix
		// WA lists fields by their YAML label, so an empty label falls back to the name.
		label := strings.TrimSpace(propString(n, "label"))
		if label == "" {
			label = strings.ReplaceAll(propString(n, "name"), "_", " ")
		}
		if suffix != "" {
			label += " " + suffix[1:]
		}
		desc := propString(n, "description")
		if desc == "" {
			desc = label
		} else if suffix != "" {
			desc += " " + suffix[1:]
		}
		fmt.Fprintf(&b, "  %s:\n    label: %s\n", name, yamlStr(label))
		ft := propString(n, "fieldType")
		input := map[string]string{
			"string": "string", "number": "integer", "text": "text", "checkbox": "checkbox",
			"select": "select", "suggest": "string", "image": "integer",
		}[ft]
		fmt.Fprintf(&b, "    input: %s\n    description: %s\n", input, yamlStr(desc))
		if propBool(n, "required") {
			b.WriteString("    required: true\n")
		}
		switch ft {
		case "number":
			if v, ok := propNumber(n, "min"); ok {
				fmt.Fprintf(&b, "    min: %s\n", num(v))
			}
			if v, ok := propNumber(n, "max"); ok {
				fmt.Fprintf(&b, "    max: %s\n", num(v))
			}
		case "text":
			fmt.Fprintf(&b, "    rows: %s\n", num(textRows(n)))
		case "image":
			b.WriteString("    render: image\n")
		case "select":
			b.WriteString("    options:\n")
			for _, o := range propStrings(n, "options") {
				fmt.Fprintf(&b, "      %s: %s\n", yamlStr(o), yamlStr(o))
			}
		}
	})
	return b.String()
}

func textRows(n *Node) float64 {
	if r, ok := propNumber(n, "rows"); ok {
		return r
	}
	return 3
}

// repeatCount is how often a list block repeats (props.repeat), or 1.
func repeatCount(n *Node) int {
	if v, ok := propNumber(n, "repeat"); ok && v > 1 {
		return int(v)
	}
	return 1
}

// maxListNumber is the highest entry number of a list (bible 11).
const maxListNumber = 199

// repeatStart is the number of a list's first entry (props.repeatStart), default 1.
// A long list split over several cards uses e.g. 1..20, 21..40, 41..60.
func repeatStart(n *Node) int {
	if v, ok := propNumber(n, "repeatStart"); ok && v >= 1 {
		return int(v)
	}
	return 1
}

// eachFieldEntry calls fn once per WA field: a field in a list of N once per entry,
// with suffix "_001" … ("" outside lists).
func eachFieldEntry(root *Node, fn func(n *Node, suffix string)) {
	var walk func(n *Node, start, count int)
	walk = func(n *Node, start, count int) {
		if c := repeatCount(n); c > 1 {
			start, count = repeatStart(n), c
		}
		if n.Type == "field" {
			if count > 1 {
				for i := start; i < start+count; i++ {
					fn(n, fmt.Sprintf("_%03d", i))
				}
			} else {
				fn(n, "")
			}
		}
		for _, c := range n.Children {
			walk(c, start, count)
		}
	}
	walk(root, 1, 1)
}

func eachField(n *Node, fn func(*Node)) {
	if n.Type == "field" {
		fn(n)
	}
	for _, c := range n.Children {
		eachField(c, fn)
	}
}

// ---------- Twig ----------

type twigGen struct {
	b       strings.Builder
	form    bool
	sheet   string
	classes map[string]string // node id → format class (f-N)
	fields  map[string]*Node  // field node id → field, for field labels
	loop    bool              // inside a {% for %} list: field names get _{{id}}
	inList  map[string]bool   // field ids inside a list
}

// cls returns " f-N" for a formatted element, or "".
func (g *twigGen) cls(n *Node) string {
	if c := g.classes[n.ID]; c != "" {
		return " " + c
	}
	return ""
}

// attr returns " class='f-N'" for a formatted element, or "".
func (g *twigGen) attr(n *Node) string {
	if c := g.classes[n.ID]; c != "" {
		return " class='" + c + "'"
	}
	return ""
}

func (g *twigGen) line(depth int, s string) {
	g.b.WriteString(strings.Repeat("  ", depth))
	g.b.WriteString(s)
	g.b.WriteString("\n")
}

// genTwig writes the view (form=false) or the edit form (form=true).
func genTwig(p *Project, form bool) string {
	classes, _ := formatClasses(p)
	g := &twigGen{form: form, sheet: p.SheetName, classes: classes, fields: map[string]*Node{}}
	eachField(p.Root, func(n *Node) { g.fields[n.ID] = n })
	g.inList = map[string]bool{}
	eachFieldEntry(p.Root, func(n *Node, suffix string) {
		if suffix != "" {
			g.inList[n.ID] = true
		}
	})
	g.node(p.Root, nil, 0)
	return g.b.String()
}

func colClass(n *Node) string {
	var cls []string
	for _, k := range []struct{ key, prefix string }{{"col", "col-"}, {"md", "col-md-"}, {"lg", "col-lg-"}} {
		if v, ok := propNumber(n, k.key); ok && v > 0 {
			cls = append(cls, k.prefix+num(v))
		}
	}
	if len(cls) == 0 {
		return "col"
	}
	return strings.Join(cls, " ")
}

// onlyText reports whether all children are texts, so the element fits on one line.
func onlyText(n *Node) bool {
	for _, c := range n.Children {
		if c.Type != "text" {
			return false
		}
	}
	return true
}

func (g *twigGen) joinedText(n *Node) string {
	var parts []string
	for _, c := range n.Children {
		t := esc(propString(c, "text"))
		if g.classes[c.ID] != "" {
			t = "<span" + g.attr(c) + ">" + t + "</span>"
		}
		parts = append(parts, t)
	}
	return strings.Join(parts, " ")
}

// block writes <open> children </close>, or one line if only text is inside.
func (g *twigGen) block(n *Node, depth int, open, close string) {
	if onlyText(n) {
		g.line(depth, open+g.joinedText(n)+close)
		return
	}
	g.line(depth, open)
	for _, c := range n.Children {
		g.node(c, n, depth+1)
	}
	g.line(depth, close)
}

// loopIDLine sets id to the zero-padded loop number (001, 002, …), as in the WA examples.
const loopIDLine = "{% set id = i %}{% if id < 10 %}{% set id = '0' ~ id %}{% endif %}{% if id < 100 %}{% set id = '0' ~ id %}{% endif %}"

func (g *twigGen) node(n *Node, parent *Node, depth int) {
	if count := repeatCount(n); count > 1 && !g.loop {
		// A list (bible 11): the block is written once inside a Twig loop.
		start := repeatStart(n)
		// Preset values of fields in this list: one Twig array per field, before the loop.
		eachField(n, func(f *Node) {
			if hasPreset(f) {
				var vals []string
				for _, v := range propStrings(f, "preset") {
					vals = append(vals, "'"+twigStr(v)+"'")
				}
				g.line(depth, fmt.Sprintf("{%% set preset_%s = [%s] %%}", propString(f, "name"), strings.Join(vals, ", ")))
			}
		})
		g.line(depth, fmt.Sprintf("{%% for i in %d..%d %%}", start, start+count-1))
		g.line(depth+1, loopIDLine)
		g.loop = true
		// Sheet only: an entry without any value is not shown (the form shows all entries).
		if cond := g.entryHasValue(n); cond != "" && !g.form {
			g.line(depth+1, "{% if "+cond+" %}")
			g.nodeInner(n, parent, depth+1)
			g.line(depth+1, "{% endif %}")
		} else {
			g.nodeInner(n, parent, depth+1)
		}
		g.loop = false
		g.line(depth, "{% endfor %}")
		return
	}
	g.nodeInner(n, parent, depth)
}

func (g *twigGen) nodeInner(n *Node, parent *Node, depth int) {
	switch n.Type {
	case "container":
		g.line(depth, fmt.Sprintf("<div class='container-fluid block-%s'>", g.sheet))
		for _, c := range n.Children {
			g.node(c, n, depth+1)
		}
		g.line(depth, "</div>")
	case "row":
		g.block(n, depth, "<div class='row"+g.cls(n)+"'>", "</div>")
	case "col":
		g.block(n, depth, "<div class='"+colClass(n)+g.cls(n)+"'>", "</div>")
	case "card":
		cls := "card"
		if c := propString(n, "cls"); c != "" {
			cls += " " + c
		}
		g.block(n, depth, "<div class='"+cls+g.cls(n)+"'>", "</div>")
	case "card-header":
		g.block(n, depth, "<div class='card-header"+g.cls(n)+"'>", "</div>")
	case "card-body":
		g.block(n, depth, "<div class='card-body"+g.cls(n)+"'>", "</div>")
	case "ul", "ol", "li", "tr", "th", "td":
		g.block(n, depth, "<"+n.Type+g.attr(n)+">", "</"+n.Type+">")
	case "table":
		g.block(n, depth, "<table class='table"+g.cls(n)+"'>", "</table>")
	case "text":
		// Inside a container a text gets its own element; in a header, item or cell it is
		// plain text, or a span when it is formatted.
		text := esc(propString(n, "text"))
		switch {
		case parent != nil && (parent.Type == "col" || parent.Type == "card-body"):
			g.line(depth, "<div class='txt"+g.cls(n)+"'>"+text+"</div>")
		case g.classes[n.ID] != "":
			g.line(depth, "<span"+g.attr(n)+">"+text+"</span>")
		default:
			g.line(depth, text)
		}
	case "image":
		img := "<img src='/i/" + propString(n, "imageId") + "/render' alt=''" + g.attr(n)
		if w, ok := propNumber(n, "width"); ok && w > 0 {
			img += " width='" + num(w) + "'"
		}
		g.line(depth, img+">")
	case "field":
		// In a table cell a field writes only its value; its label sits in a field label.
		g.field(n, parent != nil && (parent.Type == "th" || parent.Type == "td"), depth)
	case "flabel":
		f := g.fields[propString(n, "field")]
		if f == nil {
			return
		}
		label := esc(strings.TrimSpace(propString(f, "label")))
		if label == "" {
			return
		}
		name := propString(f, "name")
		if g.form && (g.inList[f.ID] && !g.loop || g.loop && isConstField(f)) {
			// A header label of a list field sits outside the loop: it belongs to all entries.
			g.line(depth, fmt.Sprintf("<label class='ilbl ilbl-%s'>%s</label>", fieldClass(name), label))
		} else if g.form {
			g.line(depth, fmt.Sprintf("<label class='ilbl ilbl-%s' for='%s'>%s</label>", fieldClass(name), g.nameAttr(name), label))
		} else {
			g.line(depth, fmt.Sprintf("<div class='lbl lbl-%s'>%s</div>", fieldClass(name), label))
		}
	}
}

func (g *twigGen) field(n *Node, inCell bool, depth int) {
	name := propString(n, "name")
	cls := fieldClass(name)
	label := esc(strings.TrimSpace(propString(n, "label")))
	if inCell {
		label = ""
	}
	// Without a label only the value is written.
	if g.form {
		if label != "" && g.isConst(n) {
			g.line(depth, fmt.Sprintf("<div class='ilbl ilbl-%s'>%s</div>", cls, label))
		} else if label != "" {
			g.line(depth, fmt.Sprintf("<div class='ilbl ilbl-%s'><label for='%s'>%s</label></div>", cls, g.nameAttr(name), label))
		}
		g.line(depth, fmt.Sprintf("<div class='ivar ivar-%s'>%s</div>", cls, g.formInput(n)))
		return
	}
	if label != "" {
		g.line(depth, fmt.Sprintf("<div class='lbl lbl-%s'>%s</div>", cls, label))
	}
	g.line(depth, fmt.Sprintf("<div class='var var-%s'>%s</div>", cls, g.sheetValue(n)))
}

// varExpr is the Twig expression of a field value. In a list it is attribute(variables, 'x_' ~ id).
func (g *twigGen) varExpr(name string) string {
	if g.loop {
		return "attribute(variables, '" + name + "_' ~ id)"
	}
	return "variables." + name
}

// nameAttr is the form name (and id) of a field. In a list it is x_{{id}}.
func (g *twigGen) nameAttr(name string) string {
	if g.loop {
		return name + "_{{id}}"
	}
	return name
}

// entryHasValue is the Twig condition "this list entry has a value": its data fields
// joined with "or". Empty when every entry must show: the list keeps empty entries
// (props.showEmpty), it has no data fields, or a field has preset values (they always
// have something to show).
func (g *twigGen) entryHasValue(list *Node) string {
	if propBool(list, "showEmpty") {
		return ""
	}
	var conds []string
	preset := false
	eachField(list, func(f *Node) {
		if hasPreset(f) {
			preset = true
			return
		}
		conds = append(conds, g.varExpr(propString(f, "name"))+"|default")
	})
	if preset {
		return ""
	}
	return strings.Join(conds, " or ")
}

// hasPreset: a string field with preset values (bible 11, preset values in lists).
func hasPreset(n *Node) bool {
	return n.Type == "field" && propString(n, "fieldType") == "string" && len(propStrings(n, "preset")) > 0
}

// isConstField: preset values the user cannot change. Such a field is no WA field: no input,
// no YAML entry; sheet and form show the preset text.
func isConstField(n *Node) bool {
	return hasPreset(n) && !propBool(n, "editable")
}

func (g *twigGen) isConst(n *Node) bool { return g.loop && isConstField(n) }

// presetExpr is the preset value of the current list entry. It counts by entry number, so a
// list split over cards (1..10, 11..20, …) shares one list of values: entry 11 takes value 11.
func (g *twigGen) presetExpr(n *Node) string {
	return fmt.Sprintf("preset_%s[i - 1]|default", propString(n, "name"))
}

func (g *twigGen) sheetValue(n *Node) string {
	v := g.varExpr(propString(n, "name"))
	if g.loop && hasPreset(n) {
		if isConstField(n) {
			return "{{" + g.presetExpr(n) + "}}"
		}
		return "{{" + v + "|default(" + g.presetExpr(n) + ")}}"
	}
	switch propString(n, "fieldType") {
	case "text":
		return "{{" + v + "|default|nl2br}}"
	case "checkbox":
		return "{% if " + v + "|default > 0 %}<i class='fa-regular fa-square-check'></i>{% else %}<i class='fa-regular fa-square'></i>{% endif %}"
	case "image":
		return "{% if " + v + "|default > 0 %}[img:{{" + v + "}}]{% endif %}"
	default:
		return "{{" + v + "|default}}"
	}
}

func (g *twigGen) formInput(n *Node) string {
	cls := fieldClass(propString(n, "name"))
	v := g.varExpr(propString(n, "name"))
	name := g.nameAttr(propString(n, "name"))
	listID := "list-" + cls
	if g.loop {
		listID += "-{{id}}"
	}
	value := "value='{{" + v + "|default}}'"
	if g.loop && hasPreset(n) {
		if isConstField(n) {
			return "{{" + g.presetExpr(n) + "}}"
		}
		value = "value='{{" + v + "|default(" + g.presetExpr(n) + ")}}'"
	}
	common := fmt.Sprintf("class='form-control ivar ivar-%s' id='%s' name='%s'", cls, name, name)
	req := ""
	if propBool(n, "required") {
		req = " required='required'"
	}
	ph := ""
	if s := propString(n, "placeholder"); s != "" {
		ph = " placeholder='" + esc(s) + "'"
	}
	switch propString(n, "fieldType") {
	case "number":
		attrs := ""
		if m, ok := propNumber(n, "min"); ok {
			attrs += " min='" + num(m) + "'"
		}
		if m, ok := propNumber(n, "max"); ok {
			attrs += " max='" + num(m) + "'"
		}
		return fmt.Sprintf("<input %s %s type='number'%s%s />", value, common, attrs, ph)
	case "text":
		return fmt.Sprintf("<textarea %s rows='%s'%s>{{%s|default}}</textarea>", common, num(textRows(n)), ph, v)
	case "checkbox":
		return fmt.Sprintf("<input value='0' name='%s' type='hidden' /><input value='1' {%% if %s|default > 0 %%}checked='checked'{%% endif %%} class='ivar ivar-%s' id='%s' name='%s' type='checkbox' />",
			name, v, cls, name, name)
	case "select":
		var b strings.Builder
		fmt.Fprintf(&b, "<select %s>", common)
		for _, o := range propStrings(n, "options") {
			fmt.Fprintf(&b, "<option value='%s' {%% if %s|default == '%s' %%}selected='selected'{%% endif %%}>%s</option>", esc(o), v, twigStr(o), esc(o))
		}
		b.WriteString("</select>")
		return b.String()
	case "suggest":
		var b strings.Builder
		fmt.Fprintf(&b, "<input %s list='%s' %s type='text'%s /><datalist id='%s'>", value, listID, common, ph, listID)
		for _, o := range propStrings(n, "options") {
			fmt.Fprintf(&b, "<option value='%s'></option>", esc(o))
		}
		b.WriteString("</datalist>")
		return b.String()
	case "image":
		if ph == "" {
			ph = " placeholder='WA Image ID'"
		}
		return fmt.Sprintf("<input %s %s type='number'%s />", value, common, ph)
	default:
		return fmt.Sprintf("<input %s %s type='text'%s%s />", value, common, req, ph)
	}
}
