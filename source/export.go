// Export file names, in the order they are written.
var exportFiles = []string{"approved.css", "style.css", "import-to-wa.yml", "basic-sheet.html.twig", "edit-form.html.twig"}

const cssHeader = "/* Generated by WA Sheet Generator. Edit custom CSS in the app, not here. */\n"

// buildExport validates p and generates the five WA files (bible 1).
// Files are only returned when there are no errors.
func buildExport(p *Project) (map[string]string, []Problem) {
	ps := validateProject(p)
	if hasErrors(ps) {
		return nil, ps
	}
	files := map[string]string{
		"approved.css":          genApprovedCSS(p),
		"style.css":             genStyleCSS(p),
		"import-to-wa.yml":      genYAML(p),
		"basic-sheet.html.twig": genTwig(p, false),
		"edit-form.html.twig":   genTwig(p, true),
	}
	ps = append(ps, checkCSS("approved.css", files["approved.css"])...)
	ps = append(ps, checkCSS("style.css", files["style.css"])...)
	ps = append(ps, checkHTML("basic-sheet.html.twig", files["basic-sheet.html.twig"])...)
	ps = append(ps, checkHTML("edit-form.html.twig", files["edit-form.html.twig"])...)
	if hasErrors(ps) {
		return nil, ps
	}
	return files, ps
}

func writeExport(folder string, files map[string]string) error {
	if err := os.MkdirAll(folder, 0o755); err != nil {
		return err
	}
	for _, name := range exportFiles {
		if err := os.WriteFile(filepath.Join(folder, name), []byte(files[name]), 0o644); err != nil {
			return err
		}
	}
	return nil
}

// ---------- escaping ----------

// htmlEscaper escapes text and attribute values. Braces are escaped too,
// so user text can never become Twig code ({{ … }} or {% … %}).
var htmlEscaper = strings.NewReplacer(
	"&", "&amp;", "<", "&lt;", ">", "&gt;", `"`, "&quot;", "'", "&#39;", "{", "&#123;", "}", "&#125;",
)

func esc(s string) string { return htmlEscaper.Replace(s) }

// twigStr is the content of a single-quoted Twig string literal.
func twigStr(s string) string {
	return strings.NewReplacer(`\`, `\\`, `'`, `\'`).Replace(s)
}

func yamlStr(s string) string {
	return `"` + strings.NewReplacer(`\`, `\\`, `"`, `\"`).Replace(s) + `"`
}

func num(v float64) string { return strconv.FormatFloat(v, 'f', -1, 64) }

// fieldClass turns a field name into its class part: hp_max → hp-max.
func fieldClass(name string) string { return strings.ReplaceAll(name, "_", "-") }

// ---------- CSS ----------

func genApprovedCSS(p *Project) string {
	var b strings.Builder
	b.WriteString(cssHeader)
	for _, f := range p.Fonts {
		fmt.Fprintf(&b, "@font-face {\n  font-family: %s;\n  font-style: normal;\n  font-weight: 400;\n  src: url(%s)\n}\n", f.Name, f.URL)
	}
	if s := strings.TrimSpace(p.CustomCSS.Approved); s != "" {
		b.WriteString(s + "\n")
	}
	return b.String()
}

func genStyleCSS(p *Project) string {
	var b strings.Builder
	b.WriteString(cssHeader)
	if s := strings.TrimSpace(p.CustomCSS.Style); s != "" {
		b.WriteString(s + "\n")
	}
	return b.String()
}

// ---------- YAML ----------

func genYAML(p *Project) string {
	var b strings.Builder
	b.WriteString("fields:\n")
	eachField(p.Root, func(n *Node) {
		name := propString(n, "name")
		label := propString(n, "label")
		desc := propString(n, "description")
		if desc == "" {
			desc = label
		}
		fmt.Fprintf(&b, "  %s:\n    label: %s\n", name, yamlStr(label))
		ft := propString(n, "fieldType")
		input := map[string]string{
			"string": "string", "number": "integer", "text": "text", "checkbox": "checkbox",
			"select": "select", "suggest": "string", "image": "integer",
		}[ft]
		fmt.Fprintf(&b, "    input: %s\n    description: %s\n", input, yamlStr(desc))
		if propBool(n, "required") {
			b.WriteString("    required: true\n")
		}
		switch ft {
		case "number":
			if v, ok := propNumber(n, "min"); ok {
				fmt.Fprintf(&b, "    min: %s\n", num(v))
			}
			if v, ok := propNumber(n, "max"); ok {
				fmt.Fprintf(&b, "    max: %s\n", num(v))
			}
		case "text":
			fmt.Fprintf(&b, "    rows: %s\n", num(textRows(n)))
		case "image":
			b.WriteString("    render: image\n")
		case "select":
			b.WriteString("    options:\n")
			for _, o := range propStrings(n, "options") {
				fmt.Fprintf(&b, "      %s: %s\n", yamlStr(o), yamlStr(o))
			}
		}
	})
	return b.String()
}

func textRows(n *Node) float64 {
	if r, ok := propNumber(n, "rows"); ok {
		return r
	}
	return 3
}

func eachField(n *Node, fn func(*Node)) {
	if n.Type == "field" {
		fn(n)
	}
	for _, c := range n.Children {
		eachField(c, fn)
	}
}

// ---------- Twig ----------

type twigGen struct {
	b     strings.Builder
	form  bool
	sheet string
}

func (g *twigGen) line(depth int, s string) {
	g.b.WriteString(strings.Repeat("  ", depth))
	g.b.WriteString(s)
	g.b.WriteString("\n")
}

// genTwig writes the view (form=false) or the edit form (form=true).
func genTwig(p *Project, form bool) string {
	g := &twigGen{form: form, sheet: p.SheetName}
	g.node(p.Root, nil, 0)
	return g.b.String()
}

func colClass(n *Node) string {
	var cls []string
	for _, k := range []struct{ key, prefix string }{{"col", "col-"}, {"md", "col-md-"}, {"lg", "col-lg-"}} {
		if v, ok := propNumber(n, k.key); ok && v > 0 {
			cls = append(cls, k.prefix+num(v))
		}
	}
	if len(cls) == 0 {
		return "col"
	}
	return strings.Join(cls, " ")
}

// onlyText reports whether all children are texts, so the element fits on one line.
func onlyText(n *Node) bool {
	for _, c := range n.Children {
		if c.Type != "text" {
			return false
		}
	}
	return true
}

func joinedText(n *Node) string {
	var parts []string
	for _, c := range n.Children {
		parts = append(parts, esc(propString(c, "text")))
	}
	return strings.Join(parts, " ")
}

// block writes <open> children </close>, or one line if only text is inside.
func (g *twigGen) block(n *Node, depth int, open, close string) {
	if onlyText(n) {
		g.line(depth, open+joinedText(n)+close)
		return
	}
	g.line(depth, open)
	for _, c := range n.Children {
		g.node(c, n, depth+1)
	}
	g.line(depth, close)
}

func (g *twigGen) node(n *Node, parent *Node, depth int) {
	switch n.Type {
	case "container":
		g.line(depth, fmt.Sprintf("<div class='container-fluid block-%s'>", g.sheet))
		for _, c := range n.Children {
			g.node(c, n, depth+1)
		}
		g.line(depth, "</div>")
	case "row":
		g.block(n, depth, "<div class='row'>", "</div>")
	case "col":
		g.block(n, depth, "<div class='"+colClass(n)+"'>", "</div>")
	case "card":
		cls := "card"
		if c := propString(n, "cls"); c != "" {
			cls += " " + c
		}
		g.block(n, depth, "<div class='"+cls+"'>", "</div>")
	case "card-header":
		g.block(n, depth, "<div class='card-header'>", "</div>")
	case "card-body":
		g.block(n, depth, "<div class='card-body'>", "</div>")
	case "ul", "ol", "li", "tr", "th", "td":
		g.block(n, depth, "<"+n.Type+">", "</"+n.Type+">")
	case "table":
		g.block(n, depth, "<table class='table'>", "</table>")
	case "text":
		// Inside a container a text gets its own element; in a header, item or cell it is plain text.
		if parent != nil && (parent.Type == "col" || parent.Type == "card-body") {
			g.line(depth, "<div class='txt'>"+esc(propString(n, "text"))+"</div>")
		} else {
			g.line(depth, esc(propString(n, "text")))
		}
	case "image":
		img := "<img src='/i/" + propString(n, "imageId") + "/render' alt=''"
		if w, ok := propNumber(n, "width"); ok && w > 0 {
			img += " width='" + num(w) + "'"
		}
		g.line(depth, img+">")
	case "field":
		g.field(n, parent != nil && parent.Type == "tr", depth)
	}
}

func (g *twigGen) field(n *Node, inRow bool, depth int) {
	name := propString(n, "name")
	cls := fieldClass(name)
	label := esc(propString(n, "label"))
	lblTag, valTag := "div", "div"
	if inRow {
		lblTag, valTag = "th", "td"
	}
	if g.form {
		g.line(depth, fmt.Sprintf("<%s class='ilbl ilbl-%s'><label for='%s'>%s</label></%s>", lblTag, cls, name, label, lblTag))
		g.line(depth, fmt.Sprintf("<%s class='ivar ivar-%s'>%s</%s>", valTag, cls, formInput(n), valTag))
		return
	}
	g.line(depth, fmt.Sprintf("<%s class='lbl lbl-%s'>%s</%s>", lblTag, cls, label, lblTag))
	g.line(depth, fmt.Sprintf("<%s class='var var-%s'>%s</%s>", valTag, cls, sheetValue(n), valTag))
}

func sheetValue(n *Node) string {
	v := "variables." + propString(n, "name")
	switch propString(n, "fieldType") {
	case "text":
		return "{{" + v + "|default|nl2br}}"
	case "checkbox":
		return "{% if " + v + "|default > 0 %}<i class='fa-regular fa-square-check'></i>{% else %}<i class='fa-regular fa-square'></i>{% endif %}"
	case "image":
		return "{% if " + v + "|default > 0 %}[img:{{" + v + "}}]{% endif %}"
	default:
		return "{{" + v + "|default}}"
	}
}

func formInput(n *Node) string {
	name := propString(n, "name")
	cls := fieldClass(name)
	v := "variables." + name
	value := "value='{{" + v + "|default}}'"
	common := fmt.Sprintf("class='form-control ivar ivar-%s' id='%s' name='%s'", cls, name, name)
	req := ""
	if propBool(n, "required") {
		req = " required='required'"
	}
	switch propString(n, "fieldType") {
	case "number":
		attrs := ""
		if m, ok := propNumber(n, "min"); ok {
			attrs += " min='" + num(m) + "'"
		}
		if m, ok := propNumber(n, "max"); ok {
			attrs += " max='" + num(m) + "'"
		}
		return fmt.Sprintf("<input %s %s type='number'%s />", value, common, attrs)
	case "text":
		return fmt.Sprintf("<textarea %s rows='%s'>{{%s|default}}</textarea>", common, num(textRows(n)), v)
	case "checkbox":
		return fmt.Sprintf("<input value='0' name='%s' type='hidden' /><input value='1' {%% if %s|default > 0 %%}checked='checked'{%% endif %%} class='ivar ivar-%s' id='%s' name='%s' type='checkbox' />",
			name, v, cls, name, name)
	case "select":
		var b strings.Builder
		fmt.Fprintf(&b, "<select %s>", common)
		for _, o := range propStrings(n, "options") {
			fmt.Fprintf(&b, "<option value='%s' {%% if %s|default == '%s' %%}selected='selected'{%% endif %%}>%s</option>", esc(o), v, twigStr(o), esc(o))
		}
		b.WriteString("</select>")
		return b.String()
	case "suggest":
		var b strings.Builder
		fmt.Fprintf(&b, "<input %s list='list-%s' %s type='text' /><datalist id='list-%s'>", value, cls, common, cls)
		for _, o := range propStrings(n, "options") {
			fmt.Fprintf(&b, "<option value='%s'></option>", esc(o))
		}
		b.WriteString("</datalist>")
		return b.String()
	case "image":
		return fmt.Sprintf("<input %s %s type='number' placeholder='WA Image ID' />", value, common)
	default:
		return fmt.Sprintf("<input %s %s type='text'%s />", value, common, req)
	}
}
